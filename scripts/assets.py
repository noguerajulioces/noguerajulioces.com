"""Stack registry -> icons/ + the Stack block in index.html; also fetches the language flags.
Icons: Simple Icons (CC0). Flags: flag-icons (MIT). Safe to rerun.
Run from the project root: python3 -I scripts/assets.py"""
import pathlib, re, urllib.request, urllib.error

ROOT = pathlib.Path(__file__).resolve().parent.parent
ICON = "https://cdn.jsdelivr.net/npm/simple-icons@13.21.0/icons/{}.svg"
FLAG = "https://cdn.jsdelivr.net/npm/flag-icons@7.2.3/flags/4x3/{}.svg"
FLAGS = ["py", "es", "br", "us"]

# (label, i18n key or None, [(tool, [simple-icons slugs to try in order])])
STACK = [
    ("Backend", None, [("Ruby", ["ruby"]), ("Ruby on Rails", ["rubyonrails"]), ("Hotwire · Turbo", ["hotwire", "turbo"]),
                       ("Sidekiq", ["sidekiq"]), ("PHP", ["php"]), ("REST APIs", [])]),
    ("Data", "st-data", [("PostgreSQL", ["postgresql"]), ("MongoDB", ["mongodb"]), ("Redis", ["redis"])]),
    ("Frontend", None, [("React", ["react"]), ("Next.js", ["nextdotjs"]), ("JavaScript", ["javascript"]),
                        ("Tailwind CSS", ["tailwindcss"]), ("WordPress", ["wordpress"]), ("HTML · CSS", ["html5"])]),
    ("Cloud · DevOps", None, [("AWS EC2", ["amazonec2", "amazonaws", "amazonwebservices"]), ("AWS S3", ["amazons3", "amazonaws"]),
                              ("Elastic Beanstalk", ["awselasticbeanstalk"]), ("Firebase", ["firebase"]), ("Docker", ["docker"]),
                              ("GitHub", ["github"]), ("GitHub Actions", ["githubactions"])]),
    ("AI", "st-ai", [("Claude Code", ["claude", "anthropic"]), ("ChatGPT", ["openai"]), ("Grok", ["grok"])]),
    ("Earlier", "earlier", [("C# · .NET", ["dotnet"]), ("SQL Server", ["microsoftsqlserver"])]),
]


def fetch(url, dest):
    if dest.exists():
        return True
    try:
        data = urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "assets-script"}), timeout=20).read()
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return False
        raise
    dest.parent.mkdir(exist_ok=True)
    dest.write_bytes(data)
    return True


def icon_for(slugs):
    for slug in slugs:
        if fetch(ICON.format(slug), ROOT / "icons" / f"{slug}.svg"):
            return slug
    return None


missing = []
rows = []
for label, key, tools in STACK:
    tags = []
    for name, slugs in tools:
        slug = icon_for(slugs)
        if slugs and not slug:
            missing.append(name)
        icon = f'<i class="tool-icon" style="--icon: url(icons/{slug}.svg)" aria-hidden="true"></i>' if slug else ""
        tags.append(f'<span class="tag">{icon}{name}</span>')
    attr = f' data-i18n="{key}"' if key else ""
    rows.append(f'        <div class="stack-row"><span class="meta"{attr}>{label}</span><div class="tags">{"".join(tags)}</div></div>\n')
block = "      <!-- stack:start (generated by scripts/assets.py) -->\n      <div class=\"stack\">\n" + "".join(rows) + "      </div>\n      <!-- stack:end -->\n"

page = ROOT / "index.html"
html = page.read_text()
if "<!-- stack:start" in html:
    html = re.sub(r"      <!-- stack:start.*?<!-- stack:end -->\n", lambda _: block, html, count=1, flags=re.S)
else:
    html, n = re.subn(r'      <div class="stack">\n.*?\n      </div>\n', lambda _: block, html, count=1, flags=re.S)
    assert n == 1, "stack block not found"
page.write_text(html)

for code in FLAGS:
    assert fetch(FLAG.format(code), ROOT / "flags" / f"{code}.svg"), code

print("tools:", sum(len(t) for _, _, t in STACK), "| without icon:", ", ".join(missing) or "none")
